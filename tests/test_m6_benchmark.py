class ScriptedLLM:
    """Deterministic stub: emits one scripted tool call per turn, then ends."""

    model = "scripted"

    def __init__(self, script):
        self._script = list(script)
        self._n = 0

    def bind(self, fn):
        pass

    def tool_turn(self, messages, max_tokens=900, temperature=0.2,
                  reasoning_budget=0, tools=None, tool_choice="auto"):
        self._n += 1
        if self._script:
            name, args = self._script.pop(0)
            return {"content": "", "finish_reason": "tool_calls",
                    "tool_calls": [{"id": f"call-{self._n}", "name": name,
                                    "args": args,
                                    "raw_arguments": json.dumps(args)}]}
        return {"content": "done", "finish_reason": "stop", "tool_calls": []}

    def json(self, system, prompt, max_tokens, expected="plan",
             retries=1, reasoning_budget=0):
        raise RuntimeError("scripted planner never called in single-task mode")


