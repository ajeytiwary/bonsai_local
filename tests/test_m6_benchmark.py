def test_tier_baselines_fail(tier_root):
    """Every Tier 1-5 fixture must fail before the fix (like Tier 0)."""
    for t in _tasks():
        fix = tier_root / t["id"]
        cmd = t["test_command"]
        if t.get("hidden_check"):
            cmd = f"{cmd} && {t['hidden_check']}"
        r = subprocess.run(cmd, cwd=fix, shell=True, text=True,
                           capture_output=True)
        assert r.returncode != 0, f"{t['id']} baseline unexpectedly passes"


