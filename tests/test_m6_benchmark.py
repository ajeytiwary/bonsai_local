def test_t604_flaky_command_recovers(monkeypatch):
    from bonsai_agent import resilience
    calls = {"n": 0}

    def attempt(_n, rid):
        calls["n"] += 1
        if calls["n"] == 1:
            raise resilience.AttemptError(
                kind="timeout", status_code=None, attempts=1,
                request_id=rid, excerpt="timed out")
