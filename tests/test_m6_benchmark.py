def test_t601_http_503_retry_then_success(monkeypatch):
    from bonsai_agent import resilience
    calls = {"n": 0}

    def attempt(_n, rid):
        calls["n"] += 1
        if calls["n"] < 3:
            raise resilience.AttemptError(
                kind="http_503", status_code=503, attempts=calls["n"],
                request_id=rid, excerpt="Service Unavailable")
        return "ok"

    monkeypatch.setattr(resilience.time, "sleep", lambda s: None)
    (out, meta) = resilience.call_with_retry(
        attempt, resilience.RetryConfig(max_retries=3, base_delay=0.01,
                                        max_delay=0.05))
    assert out == "ok" and meta["retries"] == 2


