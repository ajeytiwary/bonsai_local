def test_t607_interrupted_session_checkpoint(tmp_path):
    from bonsai_agent import checkpoints as ck
    subprocess.run(["git", "init", "-q"], cwd=tmp_path, check=True)
    (tmp_path / "a.py").write_text("v = 1\n")
    subprocess.run(["git", "add", "."], cwd=tmp_path, check=True)
    subprocess.run(["git", "-c", "user.email=t@t", "-c", "user.name=t",
                    "commit", "-qm", "init"], cwd=tmp_path, check=True)
    head = subprocess.run(["git", "-C", str(tmp_path), "rev-parse", "HEAD"],
                          text=True, capture_output=True).stdout.strip()
    cp = ck.Checkpoint(objective="o", acceptance="a", baseline_commit=head,
                       task_owned_files=["a.py"], completed_steps=["s1"],
                       next_action="resume here")
    ck.write_checkpoint(tmp_path, 7, cp)
    back = ck.read_checkpoint(tmp_path, 7)
    assert back and back.next_action == "resume here"
    assert back.file_hashes.get("a.py")


def test_t608_conflicting_edit_rejected(tmp_path):
    from bonsai_agent.editing import AmbiguityError, Editor
    p = tmp_path / "dup.py"
    p.write_text("x = 1\nx = 1\n")
    with pytest.raises(AmbiguityError):
        Editor(tmp_path).replace_in_file("dup.py", "x = 1", "x = 2")
    assert p.read_text() == "x = 1\nx = 1\n"  # unchanged


